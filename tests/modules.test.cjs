// Distribuição precisa por largura livre e espessura da divisória.
const equal3=M.equalBays({...model,shelfCount:0},3);
const three=M.parts(equal3);
A.equal(three.bays.length,3);
A.equal(three.parts.filter(p=>p.key.startsWith('divider-')).length,2);
A(Math.max(...three.bays.map(x=>x.width))-Math.min(...three.bays.map(x=>x.width))<=0.1,'largura dos vãos iguais, com 0,1 mm de tolerância');
A(Math.abs(three.bays.reduce((a,x)=>a+x.width,0)+2*18-(800-36))<=0.1,'vão interno deve fechar com duas divisórias');
const bigger=M.parts({...equal3,width:1200});
A(Math.max(...bigger.bays.map(x=>x.width))-Math.min(...bigger.bays.map(x=>x.width))<=0.1,'ao ampliar, vãos iguais continuam iguais');
